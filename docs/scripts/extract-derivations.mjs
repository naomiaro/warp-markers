#!/usr/bin/env node
// ===========================================================================
// extract-derivations.mjs
//
// Decision 3 in HANDOFF-5: canonical prose stays in the code as rich
// comments; the docs ECHO them, they don't replace them. This script makes
// "echo" enforceable. For every comment block marked with sentinels:
//
//     // <doc id="some-id">
//     // ===========================================================================
//     // teaching prose here
//     // ===========================================================================
//     // </doc>
//
// we strip the `//` prefixes and the all-`=`/`-` rule lines, and write the
// remaining prose to `docs/.generated/<id>.md`. Pages include those partials
// via `<!--@include: ./.generated/<id>.md-->`.
//
// Net effect: edit the derivation in one place (the code comment), and the
// docs update on next build. The npm `predocs:build` hook runs this script
// before VitePress builds, so a stale partial cannot ship.
// ===========================================================================
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const outDir = resolve(here, "..", ".generated");

// Files to scan for sentinels. Order matters only for the per-file output log.
const SOURCES = [
  "01-the-math/tempo-map.js",
  "01-the-math/warp-marker.js",
  "04-meter/meter.js",
  "05-messy-data/robust.js",
];

// Match the sentinel-bounded block.
//
// Pattern explanation:
//   ^\s*//\s*<doc\s+id="([\w-]+)">\s*$    -- opening sentinel, captures id
//   ([\s\S]*?)                            -- body, non-greedy
//   ^\s*//\s*<\/doc>\s*$                  -- closing sentinel
const SENTINEL = /^\s*\/\/\s*<doc\s+id="([\w-]+)">\s*$([\s\S]*?)^\s*\/\/\s*<\/doc>\s*$/gm;

// Strip the comment prefix `// ` (or `//\t` or `//` followed by EOL) from each
// line, and drop horizontal-rule decoration lines that are made of only `=`
// or `-` characters. The result is plain Markdown prose.
function stripCommentPrefix(body) {
  const lines = body.split(/\r?\n/);
  const out = [];
  for (const line of lines) {
    // Match the leading "// " or "//" with optional whitespace before.
    const m = line.match(/^\s*\/\/ ?(.*)$/);
    if (!m) {
      // Non-comment line (blank, or stray code). Pass blank lines through;
      // drop anything else (in practice the sentinels frame only comments).
      if (/^\s*$/.test(line)) out.push("");
      continue;
    }
    const stripped = m[1];
    // Drop decoration lines: 3+ consecutive `=` or `-`, optionally with
    // leading/trailing whitespace.
    if (/^[ \t]*[=-]{3,}[ \t]*$/.test(stripped)) continue;
    out.push(stripped);
  }
  // Collapse runs of leading/trailing blank lines, but keep internal blank
  // lines (they are paragraph breaks in the source comments).
  while (out.length && out[0] === "") out.shift();
  while (out.length && out[out.length - 1] === "") out.pop();
  return out.join("\n") + "\n";
}

// ---------------------------------------------------------------------------
// Run.
// ---------------------------------------------------------------------------
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

let totalExtracted = 0;
const summary = [];
for (const rel of SOURCES) {
  const fullPath = join(repoRoot, rel);
  const src = readFileSync(fullPath, "utf8");
  let count = 0;
  for (const match of src.matchAll(SENTINEL)) {
    const id = match[1];
    const body = match[2];
    const markdown = stripCommentPrefix(body);
    const outPath = join(outDir, `${id}.md`);
    const header =
      `<!-- extracted from ${rel} by docs/scripts/extract-derivations.mjs -->\n` +
      `<!-- DO NOT EDIT this file directly; edit the comment in the source instead. -->\n\n`;
    writeFileSync(outPath, header + markdown, "utf8");
    count++;
  }
  totalExtracted += count;
  summary.push(`  ${rel}: ${count} block${count === 1 ? "" : "s"}`);
}

console.log(`extracted ${totalExtracted} derivation block(s):`);
for (const line of summary) console.log(line);
console.log(`wrote partials to ${outDir}`);
